"""Local query embeddings for dense (kNN) retrieval.

The Elasticsearch dense vectors were generated by
``darklethelong/vnlegal-lal``. Query vectors must use the same model and query
prefix; matching dimensions alone is not enough.

Supports two backends:
- PyTorch (default): LocalHFEmbedder — full torch+transformers stack.
- ONNX: LocalONNXEmbedder — onnxruntime inference, no torch required.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Protocol

DEFAULT_HF_EMBEDDING_MODEL = "darklethelong/vnlegal-lal"
DEFAULT_HF_EMBEDDING_DIMS = 1024
DEFAULT_HF_MAX_LENGTH = 1024
QUERY_PREFIX = (
    "Instruct: Given a Vietnamese legal question, "
    "retrieve relevant legal passages that answer the question\nQuery: "
)


class Embedder(Protocol):
    model: str
    dims: int | None

    def embed_query(self, text: str) -> list[float]:
        ...


class Encoder(Protocol):
    def encode(self, texts: list[str]) -> list[list[float]]:
        ...


class LocalONNXEmbedder:
    """Query embedder backed by an ONNX model and onnxruntime.

    Requires a pre-exported ONNX model (``model.onnx``) and a Hugging Face
    tokenizer directory or merged tokenizer file (``tokenizer.json``).
    Compatible with ``darklethelong/vnlegal-lal`` exported via
    ``scripts/export_vnlegal_onnx.py``.

    Does NOT require torch or transformers at runtime.
    """

    def __init__(
        self,
        *,
        model_path: str | Path,
        tokenizer_path: str | Path,
        dims: int | None = None,
        max_length: int = DEFAULT_HF_EMBEDDING_DIMS,
    ) -> None:
        self.model = str(model_path)
        self.dims = dims or DEFAULT_HF_EMBEDDING_DIMS
        self.max_length = max_length
        self._session: Any = None
        self._tokenizer: Any = None
        self._model_path = Path(model_path)
        self._tokenizer_path = Path(tokenizer_path)

    def _ensure_session(self) -> Any:
        if self._session is None:
            import onnxruntime as ort

            self._session = ort.InferenceSession(
                str(self._model_path),
                providers=["CPUExecutionProvider"],
            )
        return self._session

    def _ensure_tokenizer(self) -> Any:
        if self._tokenizer is None:
            from transformers import PreTrainedTokenizerFast

            self._tokenizer = PreTrainedTokenizerFast(
                tokenizer_file=str(self._tokenizer_path),
                # ponytail: trust the exported tokenizer's padding/token type settings
            )
        return self._tokenizer

    def embed_query(self, text: str) -> list[float]:
        embeddings = self._ensure_encoder().encode([QUERY_PREFIX + text])
        if not embeddings:
            raise RuntimeError("ONNX embedder returned no embeddings")
        embedding = embeddings[0]
        if not embedding:
            raise RuntimeError("ONNX embedder returned empty embedding")
        return [float(value) for value in embedding]

    def _ensure_encoder(self) -> "_ONNXEncoder":
        return _ONNXEncoder(
            model_path=self._model_path,
            tokenizer_path=self._tokenizer_path,
            max_length=self.max_length,
        )


class _ONNXEncoder:
    """ONNX inference encoder. Stateless — created fresh per encode call."""

    def __init__(
        self,
        *,
        model_path: Path,
        tokenizer_path: Path,
        max_length: int,
    ) -> None:
        self.model_path = model_path
        self.tokenizer_path = tokenizer_path
        self.max_length = max_length
        self._session: Any | None = None
        self._tokenizer: Any | None = None

    def encode(self, texts: list[str]) -> list[list[float]]:
        if not texts:
            return []
        session = self._get_session()
        tokenizer = self._get_tokenizer()
        inputs = tokenizer(
            texts,
            padding=True,
            truncation=True,
            max_length=self.max_length,
            return_tensors="np",
        )
        input_ids = inputs["input_ids"].astype("int64")
        attention_mask = inputs["attention_mask"].astype("int64")
        ort_inputs = {
            "input_ids": input_ids,
            "attention_mask": attention_mask,
        }
        outputs = session.run(None, ort_inputs)
        # pooled hidden states: (batch, dims)
        hidden = outputs[0]
        # normalize (same post-processing as PyTorch encoder)
        seq_len = int(attention_mask.shape[1])
        last_indices = seq_len - 1 - attention_mask.flip(dims=[1]).argmax(axis=1)
        row_indices = list(range(len(texts)))
        embeddings = hidden[row_indices, last_indices]
        # L2 normalize
        norms = (embeddings**2).sum(axis=1, keepdims=True) ** 0.5
        embeddings = embeddings / (norms + 1e-8)
        return embeddings.tolist()

    def _get_session(self) -> Any:
        if self._session is None:
            import onnxruntime as ort

            self._session = ort.InferenceSession(
                str(self.model_path),
                providers=["CPUExecutionProvider"],
            )
        return self._session

    def _get_tokenizer(self) -> Any:
        if self._tokenizer is None:
            from transformers import PreTrainedTokenizerFast

            self._tokenizer = PreTrainedTokenizerFast(
                tokenizer_file=str(self.tokenizer_path),
            )
        return self._tokenizer


class LocalHFEmbedder:
    """Query embedder backed by a local Hugging Face AutoModel."""

    def __init__(
        self,
        *,
        model: str = DEFAULT_HF_EMBEDDING_MODEL,
        dims: int | None = None,
        device: str = "auto",
        cache_dir: str | None = None,
        max_length: int = DEFAULT_HF_MAX_LENGTH,
        attn_implementation: str | None = None,
        encoder: Encoder | None = None,
    ) -> None:
        self.model = model
        self.dims = dims or DEFAULT_HF_EMBEDDING_DIMS
        self.device = device
        self.cache_dir = cache_dir
        self.max_length = max_length
        self.attn_implementation = attn_implementation
        self._encoder = encoder

    def embed_query(self, text: str) -> list[float]:
        embeddings = self._ensure_encoder().encode([QUERY_PREFIX + text])
        if not embeddings:
            raise RuntimeError("local HF embedder returned no embeddings")
        embedding = embeddings[0]
        if not embedding:
            raise RuntimeError("local HF embedder returned empty embedding")
        return [float(value) for value in embedding]

    def _ensure_encoder(self) -> Encoder:
        if self._encoder is None:
            self._encoder = _HFAutoModelEncoder(
                model=self.model,
                device=self.device,
                cache_dir=self.cache_dir,
                max_length=self.max_length,
                attn_implementation=self.attn_implementation,
            )
        return self._encoder


class _HFAutoModelEncoder:
    def __init__(
        self,
        *,
        model: str,
        device: str,
        cache_dir: str | None,
        max_length: int,
        attn_implementation: str | None,
    ) -> None:
        self.model_name = model
        self.requested_device = device
        self.cache_dir = cache_dir
        self.max_length = max_length
        self.attn_implementation = attn_implementation
        self._loaded: tuple[Any, Any, Any, str] | None = None

    def encode(self, texts: list[str]) -> list[list[float]]:
        if not texts:
            return []
        torch, tokenizer, model, device = self._load()
        inputs = tokenizer(
            texts,
            padding=True,
            truncation=True,
            max_length=self.max_length,
            return_tensors="pt",
        ).to(device)
        attention_mask = inputs["attention_mask"]
        seq_len = int(attention_mask.shape[1])
        with torch.inference_mode():
            output = model(**inputs, use_cache=False)
        last_indices = seq_len - 1 - attention_mask.flip(dims=[1]).argmax(dim=1)
        row_indices = torch.arange(len(texts), device=device)
        embeddings = output.last_hidden_state[row_indices, last_indices]
        embeddings = torch.nn.functional.normalize(embeddings.float(), p=2, dim=1)
        return embeddings.cpu().tolist()

    def _load(self) -> tuple[Any, Any, Any, str]:
        if self._loaded is not None:
            return self._loaded
        try:
            import torch
            from transformers import AutoModel, AutoTokenizer
        except ModuleNotFoundError as exc:
            raise ModuleNotFoundError(
                "Local HF dense retrieval requires torch and transformers in the "
                "backend environment."
            ) from exc

        device = self._resolve_device(torch)
        dtype = torch.float16 if device.startswith("cuda") else torch.float32
        tokenizer = AutoTokenizer.from_pretrained(
            self.model_name,
            cache_dir=self.cache_dir,
        )
        if tokenizer.pad_token_id is None:
            tokenizer.pad_token = tokenizer.eos_token
        model_kwargs: dict[str, Any] = {
            "cache_dir": self.cache_dir,
            "dtype": dtype,
        }
        if self.attn_implementation:
            model_kwargs["attn_implementation"] = self.attn_implementation
        model = AutoModel.from_pretrained(self.model_name, **model_kwargs)
        model.to(device)
        model.eval()
        model.config.use_cache = False
        self._loaded = (torch, tokenizer, model, device)
        return self._loaded

    def _resolve_device(self, torch: Any) -> str:
        requested = self.requested_device.strip().lower()
        if requested in {"", "auto"}:
            return "cuda" if torch.cuda.is_available() else "cpu"
        return self.requested_device
